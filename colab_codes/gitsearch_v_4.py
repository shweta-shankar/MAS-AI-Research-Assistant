def search(query, lines, top_k=15):
    query_embedding = embedder.encode([query])[0]

    similarities = []
    for i, chunk_embedding in enumerate(chunk_embeddings):
        similarity = np.dot(query_embedding, chunk_embedding) / (
            np.linalg.norm(query_embedding) * np.linalg.norm(chunk_embedding)
        )
        similarities.append((similarity, i))

    similarities.sort(reverse=True)

    results = []
    file_counts = {}

    for similarity_score, idx in similarities:
        chunk = chunks[idx]
        file = chunk["file"]

        # skip unknown chunks
        if file == "unknown":
            continue

        # skip chunks that are mostly HTML or image tags
        text = chunk["text"]
        if text.count("<") > 3 or text.count("img src") > 0:
            continue

        if file_counts.get(file, 0) >= 3:
            continue

        results.append({
            "file": file,
            "line_number": chunk["line_number"],
            "snippet": chunk["text"],
            "score": round(float(similarity_score), 3)
        })

        file_counts[file] = file_counts.get(file, 0) + 1

        if len(results) >= top_k:
            break

    return results

def call_llm(prompt):
    response = client.chat.completions.create(
        model="llama-3.3-70b-versatile",
        messages=[{"role": "user", "content": prompt}]
    )
    return response.choices[0].message.content

def ask_llm(question, search_results):
    context = ""
    for r in search_results:
        context += f"\nSource [{r['file']}:{r['line_number']}]\n{r['snippet']}\n---"

    prompt = f"""You are a strict retrieval-based assistant for a pediatric bone age assessment system.

STRICT RULES — follow without exception:
1. Every single sentence MUST end with a citation in the format [filename:line_number]
2. ONLY use information explicitly stated in the context below
3. NEVER use your own knowledge or outside information
4. If a claim cannot be directly supported by a source in the context, do NOT make that claim
5. If the context does not contain enough information to answer, respond with exactly:
   "The knowledge base does not contain sufficient information to answer this question."
6. Do NOT infer, extrapolate, or reason beyond what is explicitly stated in the sources

Context:
{context}

Question: {question}

Remember: If you cannot cite it from the context above, do not say it.
"""
    return call_llm(prompt)

def run_query(question):
    start = time.time()

    print("Searching knowledge base...")
    results = search(question, lines, top_k=15)

    # print scores to see what's happening
    for r in results:
        print(r["score"], r["file"], r["line_number"])

    # out of scope if best score is very low
    if results[0]["score"] < 0.1:
      print(f"Out of scope: Best match score was only {results[0]['score']}.")
      return

    # only keep results reasonably close to the top score
    top_score = results[0]["score"]
    filtered = [r for r in results if r["score"] >= top_score * 0.6]

    print(f"Relevant chunks found: {len(filtered)}")

    answer = ask_llm(question, filtered)

    end = time.time()
    print(f"\nAnswer:\n{answer}")
    print(f"\nTime taken: {(end-start)/60:.2f} mins")


# Load the sentence transformer model
embedder = SentenceTransformer('all-MiniLM-L6-v2')

chunks = []
CHUNK_SIZE = 15
OVERLAP = 3

# First pass: tag every line with its file
tagged_lines = []
current_file = "unknown"
for line in lines:
    stripped = line.strip()
    if stripped.startswith("FILE:"):
        current_file = stripped.replace("FILE:", "").strip()
        continue
    if stripped.startswith("===") or not stripped:
        continue
    tagged_lines.append({
        "file": current_file,
        "text": stripped
    })

print(f"Tagged lines: {len(tagged_lines)}")

# Second pass: create overlapping chunks
i = 0
while i < len(tagged_lines):
    chunk_slice = tagged_lines[i:i + CHUNK_SIZE]

    # use the most common file in this chunk
    file_names = [t["file"] for t in chunk_slice]
    current_file = max(set(file_names), key=file_names.count)

    chunk_text = " ".join([t["text"] for t in chunk_slice])

    chunks.append({
        "file": current_file,
        "line_number": i + 1,
        "text": chunk_text
    })

    i += CHUNK_SIZE - OVERLAP

print(f"Total chunks: {len(chunks)}")


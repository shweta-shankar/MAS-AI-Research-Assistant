def search(query, lines):
    results = []
    for i, line in enumerate(lines):
        if query.lower().replace(" ", "").replace("-", "") in line.lower().replace(" ", "").replace("-", ""):
            current_file = "unknown"
            for j in range(i, 0, -1):
                if lines[j].startswith("FILE:"):
                    current_file = lines[j].replace("FILE:", "").strip()
                    break
            start = max(0, i - 2)
            end = min(len(lines), i + 20)
            snippet = "".join(lines[start:end])
            results.append({
                "file": current_file,
                "line_number": i + 1,
                "snippet": snippet
            })
    return results


def call_llm(prompt):
    response = client.chat.completions.create(
        model="llama-3.3-70b-versatile",
        messages=[{"role": "user", "content": prompt}]
    )
    return response.choices[0].message.content


def extract_words(question):
    prompt = f"""Extract 3-5 keywords strictly from the question below.
Only use words that actually appear in the question.
Do NOT add related terms or your own knowledge.
Return ONLY a comma separated list, nothing else.

Question: {question}
"""
    return call_llm(prompt).split(",")


def filter_results(results, question):
    question_words = set(question.lower().replace("-","").replace(" ","").split())
    scored = []
    for r in results:
        snippet_words = set(r["snippet"].lower().replace("-","").replace(" ","").split())
        score = len(question_words & snippet_words)
        scored.append((score, r))
    scored.sort(key=lambda x: x[0], reverse=True)
    return [r for score, r in scored[:8]]

def ask_llm(question, search_results):
    context = ""
    for r in search_results:
        context += f"\nSource [{r['file']}:{r['line_number']}]\n{r['snippet']}\n---"

    prompt = f"""You are a strict retrieval-based assistant for a pediatric bone age assessment system.

STRICT RULES — follow without exception:
1. Every single sentence MUST end with a citation in the format [filename:line_number]
2. ONLY use information explicitly stated in the context below
3. NEVER use your own knowledge or outside information
4. If a claim cannot be directly supported by a source in the context, do NOT make that claim
5. If the context does not contain enough information to answer, respond with exactly:
   "The knowledge base does not contain sufficient information to answer this question."
6. Do NOT infer, extrapolate, or reason beyond what is explicitly stated in the sources

Context:
{context}

Question: {question}

Remember: If you cannot cite it from the context above, do not say it.
"""
    return call_llm(prompt)


def run_query(question):
    start = time.time()

    keywords = extract_words(question)
    print("Keywords:", keywords)

    results = []
    for keyword in keywords:
        results += search(keyword, lines)

    # deduplicate
    seen = set()
    unique_results = []
    for r in results:
        key = (r["file"], r["line_number"])
        if key not in seen:
            seen.add(key)
            unique_results.append(r)

    print("Unique results:", len(unique_results))

    # scope is determined by the knowledge base
    if len(unique_results) == 0:
        print("Out of scope: No relevant information found in the knowledge base.")
        return

    filtered = filter_results(unique_results, question)
    answer = ask_llm(question, filtered)

    end = time.time()
    print(f"\nAnswer:\n{answer}")
    print(f"\nTime taken: {(end-start)/60:.2f} mins")

